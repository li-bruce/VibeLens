/** Native timeline interactions on a complete, real four-user application recording. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { timeline } from '../skills/vibelens/assets/stategraph-viewer/recording.js';

const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.argv[2];
const phase = process.argv[3] || 'v1';
const flow = JSON.parse(await readFile('docs/review/dialogue-acceptance-20261031/operations-v1-repaired-boundaries/results.json', 'utf8'));
const out = path.resolve('docs/review/dialogue-acceptance-20261031/timeline-' + phase);
await mkdir(out, {recursive: true});
const browser = await chromium.launch({headless: true, executablePath: process.env.BO_BROWSER_EXECUTABLE});
const page = await browser.newPage({viewport: {width: 1520, height: 1060}});
const errors = [], checks = [];
const result = {phase, base, recordingId: flow.recordingId, checks, errors};
page.on('pageerror', error => errors.push(String(error.stack)));
const api = async route => { const response = await fetch(base + route); assert.ok(response.ok); return response.json(); };
const trace = () => page.evaluate(() => graphDebug.timeline);
const ready = () => page.waitForFunction(() => window.graphDebug?.graph && !graphDebug.layoutBusy);
const shot = name => page.screenshot({path: path.join(out, name + '.png')});
const sameCursor = async () => {
  const current = await trace();
  assert.equal(await page.locator('#replay-position').getAttribute('data-event-id'), current.eventId);
  assert.equal(await page.locator('#recording-timeline').getAttribute('data-event-id'), current.eventId);
  assert.equal(await page.evaluate(() => graphDebug.view.replay.index), current.raw);
  assert.deepEqual(JSON.parse(await page.locator('#recording-timeline').getAttribute('data-graph-transfers')), current.transfers);
  return current;
};
try {
  const before = await api('/api/view');
  const originalText = await (await fetch(base + '/api/recordings/' + flow.recordingId)).text();
  const recording = JSON.parse(originalText), items = timeline(recording);
  assert.equal(recording.status, 'stopped');
  assert.deepEqual(recording.gaps, []);
  assert.equal(recording.final.health.producer.errors, 0);
  assert.equal(recording.final.health.producer.data_errors, 0);
  assert.equal(recording.final.health.producer.dropped, 0);
  await page.goto(base + '/graph?lang=en');
  await ready();
  await page.selectOption('#analysis-view', 'business');
  await page.selectOption('#record-list', flow.recordingId);
  await page.waitForSelector('#recording-timeline canvas', {state: 'visible'});
  await page.selectOption('#replay-grain', 'events');
  await page.selectOption('.trace-scope', 'all');
  await page.click('.trace-fit');
  const canvas = page.locator('#recording-timeline canvas');
  await sameCursor();
  const initial = await trace();
  assert.ok(initial.lifecycles.some(interval => interval.node === 'pending' && interval.duration > 1000));
  assert.ok(initial.routes.some(route => initial.rows[route.fromRow].layer !== initial.rows[route.toRow].layer));
  assert.ok(initial.routes.some(route => route.fromRow !== route.toRow && initial.rows[route.fromRow].layer === initial.rows[route.toRow].layer));
  checks.push({name: 'Actual durations, same-layer and cross-layer handoffs', intervals: initial.lifecycles.length, routes: initial.routes.length});
  const approvedRaw = items.findIndex(item => item.phase === 'change' && item.outputs?.state === 'approved');
  assert.ok(approvedRaw > 0, 'The real approved state change is absent');
  for (const mode of ['2D', '3D']) {
    if (await page.locator('#layered-toggle').innerText() !== mode) await page.click('#layered-toggle');
    await page.selectOption('#analysis-view', 'states');
    await page.selectOption('#replay-events', String(approvedRaw));
    await ready();
    await sameCursor();
    assert.equal(await page.evaluate(() => graphDebug.view.machine.current), 'approved');
    await page.click('.trace-inspect');
    const payload = JSON.parse(await page.locator('.trace-payload').innerText());
    assert.equal(payload.id, items[approvedRaw].id);
    assert.ok(payload.changes.some(change => change.kind === 'business' && change.after === 'approved'));
    await page.click('.trace-inspect');
    await shot('actual-approved-' + mode.toLowerCase());
    checks.push({name: mode + ' graph, actual state/value data and timeline share the exact captured event', eventId: payload.id});
  }
  if (await page.locator('#layered-toggle').innerText() !== '2D') await page.click('#layered-toggle');
  await page.selectOption('#analysis-view', 'data-operations');
  await page.click('#show-all'); await page.click('#expand');
  const queryRaw = items.findIndex(item => item.node === 'db_read' && item.phase === 'return');
  assert.ok(queryRaw > 0);
  await page.selectOption('#replay-events', String(queryRaw));
  await ready();
  const dataTrace = await sameCursor();
  assert.ok(dataTrace.transfers.length, 'The actual query result has no mapped graph transfer');
  const animated = await page.locator('#semantic-edges [data-edge-id]').evaluateAll(elements => elements.filter(element => element.dataset.payload).map(element => element.dataset.edgeId).sort());
  assert.deepEqual(animated, [...dataTrace.transfers].sort());
  checks.push({name: 'Real query result animates the same evidence-supported edges', transfers: dataTrace.transfers});
  await page.selectOption('#analysis-view', 'business');
  const loginRaw = items.findIndex(item => item.node === 'login' && item.phase === 'enter');
  await page.selectOption('#replay-events', String(loginRaw));
  await page.click('.trace-maximize');
  await page.waitForFunction(() => document.querySelector('#recording-timeline').classList.contains('trace-maximized'));
  await page.click('.trace-fit');
  let current = await trace(), box = await canvas.boundingBox();
  const interval = current.lifecycles.find(item => item.entryEventId === items[loginRaw].id);
  const width = current.window.end - current.window.start;
  const time = current.points.find(point => point.raw === loginRaw).time;
  const x = box.x + current.geometry.left + (time - current.window.start) / width * current.geometry.plot;
  const factor = Math.max(16, width / Math.max(1, interval.duration * 6));
  await page.mouse.move(x, box.y + 38);
  await page.keyboard.down('Control');
  await page.mouse.wheel(0, -Math.log(factor) / 0.005);
  await page.keyboard.up('Control');
  await page.waitForFunction(old => !graphDebug.timeline.zooming && graphDebug.timeline.window.end - graphDebug.timeline.window.start < old / 10, width);
  current = await trace();
  await shot('actual-local-call-lifetimes');
  assert.ok(current.routes.some(route => route.type === 'call'));
  await canvas.focus(); await canvas.press('ArrowRight');
  await page.waitForFunction(raw => graphDebug.timeline.raw !== raw, loginRaw);
  await sameCursor();
  await page.click('.trace-fit');
  await page.waitForFunction(() => !graphDebug.timeline.zooming);
  current = await trace(); box = await canvas.boundingBox();
  await page.keyboard.down('Shift');
  await page.mouse.move(box.x + current.geometry.left + current.geometry.plot * 0.05, box.y + 38);
  await page.mouse.down();
  await page.mouse.move(box.x + current.geometry.left + current.geometry.plot * 0.3, box.y + 38, {steps: 16});
  await page.mouse.up(); await page.keyboard.up('Shift');
  assert.ok((await trace()).range[1] > (await trace()).range[0]);
  await page.click('.trace-loop');
  assert.equal(await page.locator('#replay-loop').isChecked(), true);
  await page.click('.trace-clear');
  assert.equal(await page.locator('#replay-loop').isChecked(), false);
  checks.push({name: 'Native smooth zoom, ruler seek, keyboard and interval-to-loop selection'});
  const cursor = (await trace()).eventId;
  await page.selectOption('.trace-depth', 'rules');
  let limited = await trace();
  assert.ok(limited.rows.every(row => ['business', 'state', 'rules'].includes(row.layer)));
  await page.click('.trace-single');
  assert.ok((await trace()).rows.every(row => row.layer === 'rules'));
  assert.equal((await trace()).eventId, cursor);
  await page.selectOption('.trace-depth', 'all');
  assert.equal(await page.locator('.trace-single').getAttribute('aria-pressed'), 'false');
  checks.push({name: 'Bottom-up observation depth and single layer keep the original cursor'});
  await page.click('.trace-maximize');
  await page.click('#replay-steps-toggle');
  const skipped = items[queryRaw].id;
  await page.locator(`#replay-step-list input[data-event-id="${skipped}"]`).uncheck();
  assert.equal((await trace()).points.some(point => point.raw === queryRaw), false);
  await page.locator(`#replay-step-list input[data-event-id="${skipped}"]`).check();
  assert.equal((await trace()).points.some(point => point.raw === queryRaw), true);
  await page.click('#replay-steps-toggle');
  await page.selectOption('#replay-events', String(loginRaw));
  await page.selectOption('#replay-speed', '300');
  await page.click('#replay-play');
  await page.waitForFunction(raw => graphDebug.timeline.raw !== raw, loginRaw);
  await sameCursor();
  await page.click('#replay-play');
  const held = (await trace()).eventId;
  await page.waitForTimeout(700);
  assert.equal((await trace()).eventId, held);
  checks.push({name: 'Skip/restore actual events; playback advances and pause holds one original step'});
  await page.goto(base + '/graph?lang=zh-CN');
  await ready();
  await page.selectOption('#record-list', flow.recordingId);
  await page.waitForSelector('#recording-timeline', {state: 'visible'});
  await page.setViewportSize({width: 430, height: 850});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await shot('actual-mobile-zh');
  assert.equal(await page.locator('.trace-loop').innerText(), '循环选区');
  await page.click('#replay-live');
  await page.waitForFunction(() => !graphDebug.view.replay);
  const after = await api('/api/view');
  assert.deepEqual(after.events.map(event => event.id), before.events.map(event => event.id));
  assert.equal(await (await fetch(base + '/api/recordings/' + flow.recordingId)).text(), originalText);
  assert.deepEqual(errors, []);
  checks.push({name: 'Chinese/mobile/live return preserves recording bytes and adds zero business events'});
  result.passed = true;
} catch (error) {
  result.passed = false;
  result.error = String(error.stack);
  await shot('failure').catch(() => {});
  console.error(result.error);
} finally {
  await writeFile(path.join(out, 'results.json'), JSON.stringify(result, null, 2));
  await browser.close();
}
console.log(JSON.stringify({passed: result.passed, checks: checks.length, error: result.error}));
if (!result.passed) process.exitCode = 1;
